    pos_T	old_pos;
    pos_T	par_pos;
    pos_T	దొరికింది_pos;
    పూర్ణాంకం		t;
    పూర్ణాంకం		save_p_ws;
    పూర్ణాంకం		save_p_scs;
    పూర్ణాంకం		retval = OK;
    పూర్ణాంకం		incll;
